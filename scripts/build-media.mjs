import { existsSync } from 'node:fs';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { builtinModules } from 'node:module';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import * as esbuild from 'esbuild';

export const MEDIA_VENDORS = [
  'openai',
  'google',
  'ark',
  'xai',
  'minimax',
  'stepfun',
  'novita',
  'agnes',
  'newapi',
  'comfyui',
];

const BUILTIN_SET = new Set(builtinModules.map((name) => name.replace(/^node:/, '')));
const normalize = (text) => text.replaceAll('\r\n', '\n');

function isNodeBuiltin(specifier) {
  return BUILTIN_SET.has(specifier.replace(/^node:/, ''));
}

async function syncTextFile(targetPath, expectedContent, { check, label }) {
  const normalized = normalize(expectedContent);
  if (check) {
    let actual;
    try {
      actual = normalize(await readFile(targetPath, 'utf8'));
    } catch (error) {
      if (error.code === 'ENOENT') {
        throw new Error(`Missing generated media artifact (${label}): ${targetPath}. Run \`npm run build:media\`.`);
      }
      throw error;
    }
    if (actual !== normalized) {
      throw new Error(`Generated media artifact drift (${label}): ${targetPath}. Run \`npm run build:media\`.`);
    }
    return;
  }
  await mkdir(path.dirname(targetPath), { recursive: true });
  await writeFile(targetPath, normalized, 'utf8');
}

async function bundlePlugin({ pluginsRoot, pluginId, check }) {
  const pluginDir = path.join(pluginsRoot, 'official', pluginId);
  const srcEntry = path.join(pluginDir, 'src', 'index.mjs');
  const outFile = path.join(pluginDir, 'dist', 'index.mjs');
  const manifestPath = path.join(pluginDir, 'kimi.plugin.json');

  if (!existsSync(srcEntry)) {
    throw new Error(`Missing media plugin source entrypoint: ${srcEntry}`);
  }
  const manifest = JSON.parse(await readFile(manifestPath, 'utf8'));
  if (manifest['x-kiki']?.entry !== './dist/index.mjs') {
    throw new Error(
      `Manifest ${manifestPath} must declare x-kiki.entry as "./dist/index.mjs" (got ${JSON.stringify(manifest['x-kiki']?.entry)})`,
    );
  }

  const banner = `// GENERATED by scripts/build-media.mjs for ${pluginId} — do not edit directly.`;
  const result = await esbuild.build({
    absWorkingDir: pluginsRoot,
    entryPoints: [srcEntry],
    bundle: true,
    write: false,
    platform: 'node',
    target: 'node24',
    format: 'esm',
    minify: true,
    legalComments: 'none',
    metafile: true,
    logLevel: 'silent',
    banner: { js: banner },
  });

  if (result.outputFiles.length !== 1) {
    throw new Error(`Expected exactly one bundle output for ${pluginId}, got ${result.outputFiles.length}`);
  }

  for (const output of Object.values(result.metafile.outputs)) {
    for (const imported of output.imports) {
      if (!isNodeBuiltin(imported.path)) {
        throw new Error(`Non-builtin import "${imported.path}" leaked into self-contained bundle for ${pluginId}`);
      }
    }
  }

  const code = normalize(result.outputFiles[0].text);
  await syncTextFile(outFile, code, { check, label: `${pluginId}/dist/index.mjs` });
  return { pluginId, outFile, bytes: Buffer.byteLength(code, 'utf8') };
}

function assertNoLegacyCopies(pluginsRoot) {
  const officialRoot = path.join(pluginsRoot, 'official');
  const forbidden = [
    path.join(officialRoot, 'kiki-media', 'entry.mjs'),
    path.join(officialRoot, 'kiki-media', 'lib', 'runtime.mjs'),
    path.join(officialRoot, 'kiki-media', 'lib', 'sources'),
  ];
  for (const vendor of MEDIA_VENDORS) {
    const dir = path.join(officialRoot, `kiki-media-${vendor}`);
    forbidden.push(
      path.join(dir, 'runtime.mjs'),
      path.join(dir, 'entry.mjs'),
      path.join(dir, 'adapters.mjs'),
    );
  }
  const present = forbidden.filter((candidate) => existsSync(candidate));
  if (present.length > 0) {
    throw new Error(
      `Forbidden legacy copied media files detected (single-source media-runtime build required):\n  - ${present.join('\n  - ')}`,
    );
  }
}

export async function buildMediaPlugins({
  pluginsRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', 'plugins'),
  check = false,
} = {}) {
  const officialRoot = path.join(pluginsRoot, 'official');
  const runtimeDir = path.join(officialRoot, 'media-runtime');
  for (const required of ['runtime.mjs', 'entry.mjs', 'LICENSE', 'NOTICE']) {
    if (!existsSync(path.join(runtimeDir, required))) {
      throw new Error(`Canonical media-runtime file missing: ${path.join(runtimeDir, required)}`);
    }
  }

  assertNoLegacyCopies(pluginsRoot);

  const [licenseText, noticeText] = await Promise.all([
    readFile(path.join(runtimeDir, 'LICENSE'), 'utf8'),
    readFile(path.join(runtimeDir, 'NOTICE'), 'utf8'),
  ]);

  for (const vendor of MEDIA_VENDORS) {
    const vendorDir = path.join(officialRoot, `kiki-media-${vendor}`);
    await syncTextFile(path.join(vendorDir, 'LICENSE'), licenseText, { check, label: `kiki-media-${vendor}/LICENSE` });
    await syncTextFile(path.join(vendorDir, 'NOTICE'), noticeText, { check, label: `kiki-media-${vendor}/NOTICE` });
  }

  const targets = [...MEDIA_VENDORS.map((vendor) => `kiki-media-${vendor}`), 'kiki-media'];
  const outputs = await Promise.all(
    targets.map((pluginId) => bundlePlugin({ pluginsRoot, pluginId, check })),
  );
  return { outputs, count: outputs.length };
}

function parseArgs(argv) {
  const options = { check: false, pluginsRoot: undefined };
  for (let i = 0; i < argv.length; i++) {
    const arg = argv[i];
    if (arg === '--check') {
      options.check = true;
    } else if (arg === '--plugins-root') {
      const value = argv[++i];
      if (!value || value.startsWith('--')) throw new Error('--plugins-root requires a directory path');
      options.pluginsRoot = path.resolve(value);
    } else {
      throw new Error(`Unknown argument: ${arg}`);
    }
  }
  return options;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const options = parseArgs(process.argv.slice(2));
  const { outputs } = await buildMediaPlugins(options);
  console.log(
    `${options.check ? 'Checked' : 'Built'} ${outputs.length} self-contained media plugin bundle(s) from single-source media-runtime`,
  );
}
