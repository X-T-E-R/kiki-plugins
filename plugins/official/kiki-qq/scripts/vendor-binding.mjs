import assert from 'node:assert/strict';
import { readFile, mkdir, writeFile, copyFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

// Prepare only under the repository's ignored .tmp, never the managed plugin:
// npm install --prefix .tmp/qq-binding-deps --ignore-scripts --save-exact @tencent-connect/qqbot-connector@1.2.0 qrcode@1.5.4 qrcode-terminal@0.12.0 dijkstrajs@1.0.3 esbuild@0.25.12
const root = fileURLToPath(new URL('../../../../', import.meta.url));
const modules = path.join(root, '.tmp/qq-binding-deps/node_modules');
const destination = fileURLToPath(new URL('../vendor/qqbot-binding/', import.meta.url));
const { build } = await import(pathToFileURL(path.join(modules, 'esbuild/lib/main.js')));
const packages = [
  ['@tencent-connect/qqbot-connector', '1.2.0', []],
  ['qrcode-terminal', '0.12.0', ['LICENSE']],
  ['qrcode', '1.5.4', ['license']],
  ['dijkstrajs', '1.0.3', ['LICENSE.md']],
];
for (const [name, version, licenses] of packages) {
  const source = path.join(modules, name);
  const metadata = JSON.parse(await readFile(path.join(source, 'package.json'), 'utf8'));
  assert.equal(metadata.version, version);
  const dir = path.join(destination, 'metadata', name.replace('@', '').replace('/', '-'));
  await mkdir(dir, { recursive: true });
  await copyFile(path.join(source, 'package.json'), path.join(dir, 'package.json'));
  for (const license of licenses) await copyFile(path.join(source, license), path.join(dir, license));
}
const qrNotice = (await readFile(path.join(modules, 'qrcode-terminal/vendor/QRCode/index.js'), 'utf8')).split('\n').slice(0, 15).join('\n');
await writeFile(path.join(destination, 'metadata/qrcode-terminal/QRCode-NOTICE.txt'), `${qrNotice}\n\n${(await readFile(path.join(modules, 'qrcode/license'), 'utf8')).replace(/Copyright[^\n]*/, 'Copyright (c) 2009 Kazuhiko Arase')}\n`);
const at = name => JSON.stringify(path.join(modules, name).replaceAll('\\', '/'));
await build({
  stdin: { contents: `export { startQrConnect } from ${at('@tencent-connect/qqbot-connector/dist/esm/index.js')};\nimport qr from ${at('qrcode/lib/core/qrcode.js')};\nimport svg from ${at('qrcode/lib/renderer/svg-tag.js')};\nexport function renderQrDataUrl(url) { return 'data:image/svg+xml;base64,' + Buffer.from(svg.render(qr.create(url, { errorCorrectionLevel: 'M' }), { margin: 4, width: 256 })).toString('base64'); }`, resolveDir: root, sourcefile: 'binding-entry.mjs' },
  outfile: path.join(destination, 'binding.mjs'), bundle: true, platform: 'node', format: 'esm', target: 'node18',
  minify: true, legalComments: 'eof', banner: { js: '// Generated by scripts/vendor-binding.mjs. Third-party metadata and licenses are preserved in ./metadata; see ../../NOTICE.' },
});
await writeFile(path.join(destination, 'provenance.json'), `${JSON.stringify({
  connector: { package: '@tencent-connect/qqbot-connector', version: '1.2.0', source: 'https://registry.npmjs.org/@tencent-connect/qqbot-connector/-/qqbot-connector-1.2.0.tgz', license: 'UNLICENSED', units: ['dist/esm/index.js', 'dist/esm/qr-connect.js', 'dist/esm/qqbot-session.js'], modifications: 'Bundled without protocol changes; terminal output disabled by caller.' },
  reference: { repository: 'https://github.com/tencent-connect/dsh-qqbot', version: '0.5.3', revision: 'd998f72fb4ab5492eaab3c5e1cc9de1d7901e8a9', unit: 'src/setup/binding-service.ts', license: 'MIT' },
  dependencies: packages.slice(1).map(([name, version]) => ({ name, version })),
  qrUnits: ['qrcode/lib/core', 'qrcode/lib/renderer/svg-tag.js', 'qrcode/lib/renderer/utils.js', 'dijkstrajs/dijkstra.js'],
  build: { package: 'esbuild', version: '0.25.12' },
}, null, 2)}\n`);
